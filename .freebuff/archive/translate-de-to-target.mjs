// Sort keys longest-first for each locale
for (const locale of Object.keys(DICTS)) {
  const keys = Object.keys(DICTS[locale]).sort((a, b) => b.length - a.length);
  DICTS[locale]._sortedKeys = keys;
}

// ─── Translation function ───────────────────────────────────────────────────
function translate(content, locale) {
  const dict = DICTS[locale];
  if (!dict || dict._sortedKeys?.length === 0) return content;
  const keys = dict._sortedKeys;
  let result = content;
  let inCodeBlock = false;
  const lines = result.split('\n');
  const out = [];
  
  for (const line of lines) {
    const trimmed = line.trimStart();
    if (trimmed.startsWith('```') || trimmed.startsWith('~~~')) {
      inCodeBlock = !inCodeBlock;
      out.push(line);
      continue;
    }
    if (inCodeBlock) {
      out.push(line);
      continue;
    }
    
    let l = line;
    for (const key of keys) {
      if (l.includes(key)) {
        l = l.replaceAll(key, dict[key]);
      }
    }
    out.push(l);
  }
  return out.join('\n');
}

